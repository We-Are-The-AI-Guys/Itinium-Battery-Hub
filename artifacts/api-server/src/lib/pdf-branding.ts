import PDFDocument from "pdfkit";
import path from "path";
import fs from "fs";
import { fileURLToPath } from "url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const LOGO_PATH = path.resolve(__dirname, "../../../../attached_assets/itinium-logo-transparent_1773848738567.png");

if (!fs.existsSync(LOGO_PATH)) {
  console.warn(`[pdf-branding] Itinium logo not found at: ${LOGO_PATH}`);
}
const NAVY = "#0f2744";
const TEAL = "#0ea5e9";
const HEADER_H = 68;
const MARGIN = 40;

type Doc = InstanceType<typeof PDFDocument>;

function logoExists(): boolean {
  try {
    return fs.existsSync(LOGO_PATH);
  } catch {
    return false;
  }
}

export function drawPageHeader(doc: Doc, docTitle: string, docSubtitle?: string) {
  doc.save();

  doc.rect(0, 0, doc.page.width, HEADER_H).fill(NAVY);

  let logoEndX = MARGIN + 10;
  if (logoExists()) {
    try {
      doc.image(LOGO_PATH, 18, 9, { height: 50 });
      logoEndX = 155;
    } catch {
    }
  }

  const rightW = doc.page.width - logoEndX - 16;

  doc.fillColor("#ffffff").fontSize(14).font("Helvetica-Bold")
    .text("Itinium Battery Portal", logoEndX, 13, { width: rightW, align: "right", lineBreak: false });

  if (docTitle) {
    doc.fillColor(TEAL).fontSize(10).font("Helvetica")
      .text(docTitle, logoEndX, 32, { width: rightW, align: "right", lineBreak: false });
  }

  if (docSubtitle) {
    doc.fillColor("#94a3b8").fontSize(8).font("Helvetica")
      .text(docSubtitle, logoEndX, 49, { width: rightW, align: "right", lineBreak: false });
  }

  doc.rect(0, HEADER_H, doc.page.width, 3).fill(TEAL);

  doc.restore();

  doc.x = MARGIN;
  doc.y = HEADER_H + 3 + 18;
}

export function drawPageFooter(doc: Doc, pageNum: number, totalPages: number) {
  doc.save();

  const footerY = doc.page.height - 38;

  doc.moveTo(MARGIN, footerY - 6)
    .lineTo(doc.page.width - MARGIN, footerY - 6)
    .strokeColor("#e2e8f0")
    .lineWidth(0.5)
    .stroke();

  doc.fillColor("#94a3b8").fontSize(8).font("Helvetica")
    .text(
      `Generated by Itinium Battery Portal — ${new Date().toLocaleString("en-GB")}`,
      MARGIN,
      footerY,
      { width: doc.page.width - MARGIN * 2 - 60, align: "left", lineBreak: false }
    );

  doc.fillColor("#94a3b8").fontSize(8).font("Helvetica")
    .text(
      `Page ${pageNum} of ${totalPages}`,
      MARGIN,
      footerY,
      { width: doc.page.width - MARGIN * 2, align: "right", lineBreak: false }
    );

  doc.restore();
}

export function createBrandedDoc(docTitle: string, docSubtitle?: string): {
  doc: InstanceType<typeof PDFDocument>;
  finalize: () => void;
} {
  const doc = new PDFDocument({ size: "A4", margin: MARGIN, bufferPages: true });

  drawPageHeader(doc, docTitle, docSubtitle);

  doc.on("pageAdded", () => {
    drawPageHeader(doc, docTitle, docSubtitle);
  });

  function finalize() {
    const range = doc.bufferedPageRange();
    const total = range.count;
    for (let i = 0; i < total; i++) {
      doc.switchToPage(range.start + i);
      drawPageFooter(doc, i + 1, total);
    }
    doc.flushPages();
    doc.end();
  }

  return { doc, finalize };
}
